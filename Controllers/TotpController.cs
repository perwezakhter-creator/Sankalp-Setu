using System.Threading.Tasks;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using SankalpAPI.Model;
using SankalpAPI.Services;

namespace SankalpAPI.Controllers
{
    [ApiController]
    [Route("api/[controller]")]
    [Produces("application/json")]
    [Consumes("application/json")]
    [AllowAnonymous]
    public class TotpController : ControllerBase
    {
        private readonly TotpService _totpService;

        public TotpController(TotpService totpService)
        {
            _totpService = totpService;
        }

        /// <summary>
        /// Steps 2 & 3: Check if user exists for selected web-app, generate OTP, send via SMS, and inform mobile app.
        /// </summary>
        [HttpPost("InitiateRegistration")]
        [ProducesResponseType(typeof(InitiateRegistrationResponse), StatusCodes.Status200OK)]
        [ProducesResponseType(typeof(InitiateRegistrationResponse), StatusCodes.Status400BadRequest)]
        public async Task<IActionResult> InitiateRegistration([FromBody] InitiateRegistrationRequest request)
        {
            var response = await _totpService.InitiateRegistrationAsync(request);

            if (!response.Status)
            {
                return BadRequest(response);
            }

            return Ok(response);
        }

        /// <summary>
        /// Steps 4, 5, 6 & 7: Validate OTP, generate TOTP secret, store in web-app database, and share secret with mobile app.
        /// </summary>
        [HttpPost("ValidateOtpAndGenerateSecret")]
        [ProducesResponseType(typeof(ValidateOtpAndGenerateSecretResponse), StatusCodes.Status200OK)]
        [ProducesResponseType(typeof(ValidateOtpAndGenerateSecretResponse), StatusCodes.Status400BadRequest)]
        public async Task<IActionResult> ValidateOtpAndGenerateSecret([FromBody] ValidateOtpAndGenerateSecretRequest request)
        {
            var response = await _totpService.ValidateOtpAndGenerateSecretAsync(request);

            if (!response.Status)
            {
                return BadRequest(response);
            }

            return Ok(response);
        }

        /// <summary>
        /// Validate the 6-digit TOTP code generated by the mobile app against the stored secret key.
        /// </summary>
        [HttpPost("ValidateTotp")]
        [ProducesResponseType(typeof(ValidateTotpResponse), StatusCodes.Status200OK)]
        [ProducesResponseType(typeof(ValidateTotpResponse), StatusCodes.Status400BadRequest)]
        public async Task<IActionResult> ValidateTotp([FromBody] ValidateTotpRequest request)
        {
            var response = await _totpService.ValidateTotpAsync(request);

            if (!response.Status)
            {
                return BadRequest(response);
            }

            return Ok(response);
        }
    }
}
